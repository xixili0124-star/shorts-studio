const stylesheets=new Map();
export async function ensureFont(font,text='가나다 ABC 123',requestedWeight=null,{signal}={}) {
  if(signal?.aborted)throw new DOMException('취소됨','AbortError');
  if(typeof document==='undefined'||!document.fonts)return;
  const entry=FONTS.find(f=>f.css===font);if(!entry)return;
  const weight=requestedWeight||entry.weight,key=entry.family+':'+weight;
  if(!stylesheets.has(key)){
    const request=new Promise((resolve,reject)=>{
      const link=document.createElement('link');link.rel='stylesheet';
      link.href='https://fonts.googleapis.com/css2?family='+encodeURIComponent(entry.family)+':wght@'+weight+'&display=swap';
      const timer=setTimeout(()=>{link.remove();reject(new Error(entry.label+' 폰트를 불러오지 못했습니다. 인터넷 연결을 확인해 주세요.'));},15000);
      link.onload=()=>{clearTimeout(timer);resolve();};
      link.onerror=()=>{clearTimeout(timer);link.remove();reject(new Error(entry.label+' 폰트 연결에 실패했습니다.'));};
      document.head.append(link);
    });
    stylesheets.set(key,request);
    request.catch(()=>stylesheets.delete(key));
  }
  await waitForFont(stylesheets.get(key),signal,entry.label);
  const loaded=await waitForFont(document.fonts.load(weight+' 80px '+entry.css,String(text||'가나다')),signal,entry.label);
  if(!loaded.length)throw new Error(entry.label+' 폰트가 준비되지 않았습니다. 다른 폰트를 선택하거나 연결 후 다시 시도해 주세요.');
}

function waitForFont(promise,signal,label) {
  return new Promise((resolve,reject)=>{
    if(signal?.aborted){reject(new DOMException('취소됨','AbortError'));return;}
    const cleanup=()=>{clearTimeout(timer);signal?.removeEventListener('abort',abort);};
    const abort=()=>{cleanup();reject(new DOMException('취소됨','AbortError'));};
    const timer=setTimeout(()=>{cleanup();reject(new Error(label+' 폰트 응답 시간이 초과되었습니다. 연결을 확인한 뒤 다시 시도해 주세요.'));},15000);
    signal?.addEventListener('abort',abort,{once:true});
    Promise.resolve(promise).then(value=>{cleanup();resolve(value);},error=>{cleanup();reject(error);});
  });
}

// 목록 미리보기에는 고정된 예문만 사용하고 사용자 원고는 전송하지 않습니다.
export async function ensureFontPreview(font,{signal}={}) {
  const entry=FONTS.find(item=>item.css===font||item.family===font);
  if(!entry)throw new Error('미리보기 글꼴을 찾지 못했습니다.');
  await ensureFont(entry.css,entry.previewText,entry.weight,{signal});
  return entry;
}
